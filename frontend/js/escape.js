/**
 * HTML 이스케이프 — innerHTML 로 값을 넣을 때 반드시 거친다.
 *
 * 여기 들어오는 값은 대부분 **사람이 타이핑한 것도, 우리가 만든 것도 아니다.**
 * 지점 이름은 피난안내도 사진을 AI 가 읽어 만든 것이고, 위치·구조요청 보고는
 * 인증 없는 엔드포인트로 들어온다. 그런 값이 그대로 innerHTML 에 들어가면
 * 보호자·관제 화면에서 남이 심은 스크립트가 돈다 — 구조 상황을 보고 있는
 * 화면이 조작되는 것이라, 흔한 XSS 보다 결과가 나쁘다.
 */
export function escapeHtml(s) {
  return String(s ?? '').replace(/[&<>"']/g, c =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}
